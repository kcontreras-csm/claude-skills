#!/usr/bin/env python3
"""Validates the skills in this repository and generates skills.json for Satellite's skills store.

Every top-level folder that contains a SKILL.md is a skill. Its name, description and (optional) version come
from the SKILL.md YAML frontmatter. The script checks each skill against the rules Satellite applies when it
installs one, then writes skills.json with every file's git blob SHA (so downloads are verified) and size:

    python3 scripts/generate_skills.py           # validate, then (re)write skills.json
    python3 scripts/generate_skills.py --check   # validate; fail if skills.json is out of date

Uses only the Python 3 standard library.
"""
import argparse
import hashlib
import json
import os
import re
import sys

SKILL_FILE = "SKILL.md"
INDEX = "skills.json"
COMMENT = ("Generated by scripts/generate_skills.py on every push; do not edit by hand. "
           "Add a skill by adding a folder with a SKILL.md.")

ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
SEMVER_RE = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?$")

MAX_SKILLS = 300
MAX_FILES = 100
MAX_FILE = 2_000_000
MAX_TOTAL = 20_000_000
# Files never shipped with a skill.
SKIP_DIRS = {".git", ".github", "scripts", "node_modules", ".satellite"}
SKIP_FILES = {".DS_Store"}


def fail(message):
    print("error: " + message, file=sys.stderr)
    sys.exit(1)


def git_blob_sha(data):
    """The SHA-1 git uses for a blob: sha1("blob <len>\\0" + content). Satellite verifies downloads against it."""
    h = hashlib.sha1()
    h.update(b"blob %d\0" % len(data))
    h.update(data)
    return h.hexdigest()


def read_frontmatter(path):
    """name, description and version from a SKILL.md's leading --- ... --- YAML block (simple key: value)."""
    meta = {}
    with open(path, "r", encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    if not lines or lines[0].strip() != "---":
        return meta
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip().lower()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key in ("name", "description", "version"):
            meta[key] = value
    return meta


def list_files(folder):
    """Every regular file under a skill folder, relative paths, sorted; skips junk and tooling folders."""
    files = []
    for root, dirs, names in os.walk(folder):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(names):
            if name in SKIP_FILES or (name.startswith(".") and root == folder):
                continue
            full = os.path.join(root, name)
            if os.path.islink(full):
                continue
            rel = os.path.relpath(full, folder)
            files.append(rel.replace(os.sep, "/"))
    return sorted(files)


def build_entry(skill_id, folder, problems):
    if not ID_RE.match(skill_id):
        problems.append("%s: folder name isn't a valid skill id (lowercase letters, digits, hyphens)" % skill_id)
        return None
    meta = read_frontmatter(os.path.join(folder, SKILL_FILE))
    name = meta.get("name") or skill_id
    description = meta.get("description") or ""
    version = meta.get("version") or "1.0.0"
    if not SEMVER_RE.match(version):
        problems.append("%s: version \"%s\" is not major.minor.patch" % (skill_id, version))
        return None
    if not description:
        problems.append("%s: SKILL.md frontmatter has no description" % skill_id)

    entries, total = [], 0
    paths = list_files(folder)
    if SKILL_FILE not in paths:
        problems.append("%s: no %s" % (skill_id, SKILL_FILE))
        return None
    if len(paths) > MAX_FILES:
        problems.append("%s: more than %d files" % (skill_id, MAX_FILES))
        return None
    for rel in paths:
        with open(os.path.join(folder, rel), "rb") as handle:
            data = handle.read()
        if len(data) > MAX_FILE:
            problems.append("%s: \"%s\" is larger than %d MB" % (skill_id, rel, MAX_FILE // 1_000_000))
            return None
        total += len(data)
        entries.append({"path": rel, "sha": git_blob_sha(data), "size": len(data)})
    if total > MAX_TOTAL:
        problems.append("%s: larger than %d MB in total" % (skill_id, MAX_TOTAL // 1_000_000))
        return None
    return {"id": skill_id, "name": name, "description": description, "version": version, "files": entries}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="do not write; fail if skills.json is out of date")
    args = parser.parse_args()

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(root)

    problems, skills = [], []
    for name in sorted(os.listdir(".")):
        folder = os.path.join(".", name)
        if not os.path.isdir(folder) or name in SKIP_DIRS or name.startswith("."):
            continue
        if not os.path.isfile(os.path.join(folder, SKILL_FILE)):
            continue
        entry = build_entry(name, folder, problems)
        if entry is not None:
            skills.append(entry)

    if len(skills) > MAX_SKILLS:
        problems.append("more than %d skills" % MAX_SKILLS)
    if problems:
        for problem in problems:
            print("error: " + problem, file=sys.stderr)
        sys.exit(1)

    skills.sort(key=lambda entry: entry["name"].lower())
    document = {"$comment": COMMENT, "version": 1, "skills": skills}
    text = json.dumps(document, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        current = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if current != text:
            fail("%s is out of date; run scripts/generate_skills.py" % INDEX)
        print("%s is up to date (%d skill%s)." % (INDEX, len(skills), "" if len(skills) == 1 else "s"))
    else:
        with open(INDEX, "w", encoding="utf-8") as handle:
            handle.write(text)
        print("Wrote %s (%d skill%s)." % (INDEX, len(skills), "" if len(skills) == 1 else "s"))


if __name__ == "__main__":
    main()
